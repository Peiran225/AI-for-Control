#!/usr/bin/env python3
"""Turn summary CSVs into LaTeX macros so the paper never hard-codes numbers.

Usage:
    python research/tools/make_results_macros.py research/projects/<slug>

Reads every ``09_experiments/results/summary*.csv``.  Each must have the
columns ``key,mean`` and optionally ``std,n,decimals``.  ``key`` is a
snake_case identifier such as ``robust_vi_gap_gamma09``.  For every row the
script writes to ``09_paper/results_macros.tex``:

    \\rRobustViGapGammaZeroNine        -> mean
    \\rRobustViGapGammaZeroNineStd     -> std            (if present)
    \\rRobustViGapGammaZeroNinePM      -> mean $\\pm$ std (if present)
    \\rRobustViGapGammaZeroNineN       -> n              (if present)

Digits are spelled out because LaTeX macro names may only contain letters.
"""
from __future__ import annotations

import argparse
import csv
import re
import sys
from pathlib import Path

DIGITS = ["Zero", "One", "Two", "Three", "Four", "Five", "Six", "Seven", "Eight", "Nine"]


def macro_name(key: str) -> str:
    if not re.fullmatch(r"[A-Za-z0-9_]+", key):
        raise ValueError(f"key {key!r} must be snake_case letters/digits/underscores")
    parts = []
    for token in key.split("_"):
        if not token:
            continue
        spelled = "".join(DIGITS[int(ch)] if ch.isdigit() else ch for ch in token)
        parts.append(spelled[0].upper() + spelled[1:])
    return "r" + "".join(parts)


def fmt(value: str, decimals: int) -> str:
    return f"{float(value):.{decimals}f}"


def build_macros(csv_paths: list[Path], default_decimals: int = 2) -> str:
    lines = ["% Auto-generated by research/tools/make_results_macros.py -- do not edit.", ""]
    seen: dict[str, Path] = {}
    for path in csv_paths:
        with open(path, newline="", encoding="utf-8") as fh:
            rows = list(csv.DictReader(fh))
        if rows and not {"key", "mean"} <= rows[0].keys():
            raise ValueError(f"{path.name}: needs columns key,mean")
        lines.append(f"% from {path.name}")
        for row in rows:
            name = macro_name(row["key"])
            if name in seen:
                raise ValueError(f"duplicate key {row['key']!r} in {path.name} and {seen[name].name}")
            seen[name] = path
            dec = int(row["decimals"]) if row.get("decimals") not in (None, "") else default_decimals
            mean = fmt(row["mean"], dec)
            lines.append(f"\\newcommand{{\\{name}}}{{{mean}}}")
            if row.get("std") not in (None, ""):
                std = fmt(row["std"], dec)
                lines.append(f"\\newcommand{{\\{name}Std}}{{{std}}}")
                lines.append(f"\\newcommand{{\\{name}PM}}{{{mean}\\ensuremath{{\\pm}}{std}}}")
            if row.get("n") not in (None, ""):
                lines.append(f"\\newcommand{{\\{name}N}}{{{int(float(row['n']))}}}")
        lines.append("")
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("project", type=Path)
    ap.add_argument("--decimals", type=int, default=2)
    args = ap.parse_args()
    csvs = sorted((args.project / "09_experiments" / "results").glob("summary*.csv"))
    if not csvs:
        print("no 09_experiments/results/summary*.csv found", file=sys.stderr)
        return 1
    out = args.project / "09_paper" / "results_macros.tex"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(build_macros(csvs, args.decimals), encoding="utf-8")
    print(f"wrote {out} from {len(csvs)} file(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
